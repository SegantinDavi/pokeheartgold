inline void DrawPixel(uint32_t* fb, int width, int height, int x, int y, uint32_t color) {
    if (x >= 0 && x < width && y >= 0 && y < height) {
        fb[y * width + x] = color;
    }
}

inline void FillRect(uint32_t* fb, int width, int height, int rx, int ry, int rw, int rh, uint32_t color) {
    for (int y = ry; y < ry + rh; ++y) {
        if (y < 0 || y >= height) continue;
        for (int x = rx; x < rx + rw; ++x) {
            if (x < 0 || x >= width) continue;
            fb[y * width + x] = color;
        }
    }
}

inline void DrawRect(uint32_t* fb, int width, int height, int rx, int ry, int rw, int rh, uint32_t color) {
    for (int x = rx; x < rx + rw; ++x) {
        DrawPixel(fb, width, height, x, ry, color);
        DrawPixel(fb, width, height, x, ry + rh - 1, color);
    }
    for (int y = ry; y < ry + rh; ++y) {
        DrawPixel(fb, width, height, rx, y, color);
        DrawPixel(fb, width, height, rx + rw - 1, y, color);
    }
}

inline void DrawChar(uint32_t* fb, int width, int height, int x, int y, char c, uint32_t color, int scale = 1) {
    char upper = static_cast<char>(toupper(static_cast<unsigned char>(c)));
    if (upper < 32 || upper > 95) return;
    int idx = upper - 32;

    for (int col = 0; col < 5; ++col) {
        uint8_t line = FONT_5X7[idx][col];
        for (int row = 0; row < 7; ++row) {
            if ((line >> row) & 1) {
                if (scale == 1) {
                    DrawPixel(fb, width, height, x + col, y + row, color);
                } else {
                    FillRect(fb, width, height, x + col * scale, y + row * scale, scale, scale, color);
                }
            }
        }
    }
}

inline void DrawString(uint32_t* fb, int width, int height, int x, int y, const char* str, uint32_t color, int scale = 1) {
    if (!str) return;
    int curX = x;
    while (*str) {
        DrawChar(fb, width, height, curX, y, *str, color, scale);
        curX += 6 * scale;
        str++;
    }
}

